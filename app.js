function normalize(value) {
  return value
    .toLowerCase()
    .trim()
    .replaceAll("−", "-")
    .replaceAll("×", "*")
    .replaceAll("·", "*")
    .replaceAll("⁶", "^6")
    .replaceAll("⁵", "^5")
    .replaceAll("⁴", "^4")
    .replaceAll("³", "^3")
    .replaceAll("²", "^2")
    .replace(/\s+/g, " ")
    .replace(/\s*([=+\-*/<>≤≥;,])\s*/g, "$1");
}

function numericValue(value) {
  const clean = normalize(value).replace(/^[xy]=/, "").replace(",", ".");
  if (/^-?\d+(?:\.\d+)?$/.test(clean)) return Number(clean);
  const fraction = clean.match(/^(-?\d+(?:\.\d+)?)\/(-?\d+(?:\.\d+)?)$/);
  if (!fraction || Number(fraction[2]) === 0) return null;
  return Number(fraction[1]) / Number(fraction[2]);
}

function answersMatch(candidate, answer) {
  const left = normalize(candidate);
  const right = normalize(answer);
  if (left === right) return true;
  const leftNumber = numericValue(left);
  const rightNumber = numericValue(right);
  return leftNumber !== null && rightNumber !== null && Math.abs(leftNumber - rightNumber) < 1e-9;
}

function checkAnswer(ex, raw, key) {
  const feedback = document.getElementById("feedback");
  if (!raw.trim()) {
    feedback.className = "feedback bad";
    feedback.textContent = "Сначала введите ответ. Даже предположение полезно.";
    return;
  }
  const ok = ex.a.some(answer => answersMatch(raw, answer));
  if (ok) {
    feedback.className = "feedback good";
    feedback.textContent = "Верно. Вы разобрали этот слой ✓";
    state.solved.add(key);
    const solvedHere = lessons[state.current].exercises.filter((_, i) => state.solved.has(`${state.current}-${i}`)).length;
    if (solvedHere >= 2) state.completed.add(state.current);
    saveState();
    renderNav();
  } else {
    feedback.className = "feedback bad";
    feedback.textContent = "Пока не сходится. Откройте подсказку и сделайте один следующий шаг.";
  }
}

